# Inzyght's entrypoint (images/inzyght/Dockerfile): renders inzyght.conf and config/drogon_config.json
# from the environment into INZYGHT_RUNDIR, applies and checks Inzyght's PostgreSQL schema
# (the binary does not), then execs inzyght there. Every variable is listed in images/inzyght/README.md.
# Secrets come from the environment only and are written to the run directory with mode 0600.
set -eu
APP=/opt/inzyght
RUN="${INZYGHT_RUNDIR:-/run/inzyght}"

need() { eval "v=\${$1:-}"; [ -n "$v" ] || { echo "inzyght-entrypoint: $1 is required" >&2; exit 2; }; }
# A value that goes into the INI file must be one line without a ';' or '#' comment start.
ini() { case "$2" in *"
"*|*\;*|*\#*) echo "inzyght-entrypoint: $1 must be one line without ';' or '#'" >&2; exit 2 ;; esac; }

need INZYGHT_RPC_HOST; need INZYGHT_RPC_PORT; need INZYGHT_RPC_USER; need INZYGHT_RPC_PASSWORD
need INZYGHT_PG_HOST; need INZYGHT_PG_USER; need INZYGHT_PG_PASSWORD
for k in INZYGHT_RPC_PASSWORD INZYGHT_PG_PASSWORD INZYGHT_RPC_USER INZYGHT_PG_USER; do eval "ini $k \"\$$k\""; done
# Inzyght turns a PostgreSQL host of localhost or 127.0.0.1 into the Unix socket /var/run/postgresql
# (src/main.cc), which this container does not have: give it a name or a non-loopback address.
case "$INZYGHT_PG_HOST" in localhost|127.0.0.1)
  echo "inzyght-entrypoint: INZYGHT_PG_HOST=$INZYGHT_PG_HOST means the Unix socket to Inzyght; use a host name or address it reaches over TCP" >&2; exit 2 ;;
esac

PG_PORT="${INZYGHT_PG_PORT:-5432}"
PG_DB="${INZYGHT_PG_DATABASE:-inzyght}"
PORT="${INZYGHT_PORT:-8080}"
THREADS="${INZYGHT_THREADS:-4}"
ZMQ="${INZYGHT_ZMQ_ENDPOINT:-}"
[ -n "$ZMQ" ] && ZMQ_ON=true || ZMQ_ON=false

mkdir -p "$RUN/config" "$RUN/logs"
cd "$RUN"
ln -sfn "$APP/public" "$RUN/public"
umask 077
cat > inzyght.conf <<EOF
# generated by inzyght-entrypoint from the environment; do not edit
[server]
host = 0.0.0.0
port = $PORT
threads = $THREADS
enable_logging = true
log_level = ${INZYGHT_LOG_LEVEL:-INFO}
log_path = ./logs

[database]
type = postgresql
timeout = 30

[rpc]
host = $INZYGHT_RPC_HOST
port = $INZYGHT_RPC_PORT
username = $INZYGHT_RPC_USER
password = $INZYGHT_RPC_PASSWORD
timeout = ${INZYGHT_RPC_TIMEOUT:-60.0}
ssl = false
validate_certificate = false

[zeromq]
enabled = $ZMQ_ON
endpoint = ${ZMQ:-tcp://127.0.0.1:1}
polling_fallback_timeout = ${INZYGHT_POLLING_FALLBACK_TIMEOUT:-300}
polling_interval = ${INZYGHT_POLLING_INTERVAL:-120}

[connection]
pool_size = 10
connection_timeout = 5.0
reconnect_attempts = 3

[api]
enabled = true
version = v1
max_connections = 100
max_body_size = 1048576
enable_cors = false

[postgresql]
host = $INZYGHT_PG_HOST
port = $PG_PORT
database = $PG_DB
username = $INZYGHT_PG_USER
password = $INZYGHT_PG_PASSWORD
query_pool_size = ${INZYGHT_PG_QUERY_POOL:-8}

[indexer]
block_batch_size = ${INZYGHT_BLOCK_BATCH_SIZE:-25}
block_headers_batch_size = ${INZYGHT_BLOCK_HEADERS_BATCH_SIZE:-1000}
queue_depth = ${INZYGHT_QUEUE_DEPTH:-5}

[security]
enable_ssl = false
enable_rate_limit = ${INZYGHT_RATE_LIMIT:-true}

[session]
enabled = false
timeout = 3600
storage = memory

[rate_limit]
trust_proxy = ${INZYGHT_TRUST_PROXY:-false}
trusted_proxies = ${INZYGHT_TRUSTED_PROXIES:-127.0.0.1,::1}
address_max_requests = ${INZYGHT_ADDRESS_MAX_REQUESTS:-20}
address_window_seconds = 60
api_max_requests = ${INZYGHT_API_MAX_REQUESTS:-120}
api_window_seconds = 60
EOF

# Drogon's own settings (config/drogon_config.json.example), with the listener on INZYGHT_PORT and
# TLS off: TLS is the reverse proxy's job in the explorer stack. Drogon's own log goes to stdout (an
# empty log_path: no files, so no rotated files pile up in the tmpfs) at WARN. The example's
# log_level_index / max_log_file_size / enable_auto_rotating are not keys Drogon 1.9 reads
# (lib/src/ConfigLoader.cc reads log_path, log_size_limit, max_files, log_level), so its file log
# ran at Drogon's default level, DEBUG, without a file count limit.
cat > config/drogon_config.json <<EOF
{
  "app": {
    "name": "inzyght",
    "document_root": "./public",
    "static_files_cache_time": 86400,
    "file_types": ["html","js","css","ico","png","jpg","jpeg","gif","svg","woff","woff2","ttf","eot","json","txt","mp4","webm","zip","pdf"],
    "upload_path": "$RUN/uploads",
    "max_connections": 1000,
    "client_max_body_size": "1M",
    "server_header_field": "Server: Inzyght",
    "enable_session": false,
    "session_timeout": 0,
    "log": {
      "log_path": "",
      "log_level": "WARN"
    },
    "run_as_daemon": false,
    "relaunch_on_error": false,
    "use_subprocesses": false,
    "number_of_threads": $THREADS,
    "reactor_number": 1,
    "enable_unicode_escaping_in_json": true
  },
  "listeners": [ { "address": "0.0.0.0", "port": $PORT, "https": false } ],
  "ssl": { "cert": "", "key": "", "key_password": "", "conf_commands": [] }
}
EOF
umask 022

# The schema: Inzyght's schema.sql, then schema_reorg_support.sql, in the order of its
# setup_postgresql.sh.
# - schema.sql only on a database without public.blocks, in one transaction (all or nothing).
# - schema_reorg_support.sql on EVERY start, so a start killed between the two files (or an object
#   dropped since) is repaired. It is idempotent (IF NOT EXISTS, CREATE OR REPLACE, re-runnable
#   GRANTs) except four CREATE INDEX statements without IF NOT EXISTS, three of which schema.sql
#   already made; upstream runs the file without stopping on errors, and so does this, statement by
#   statement (autocommit). Those four "already exists" errors are the only ones accepted; any other
#   error stops the container.
# - Then every table, view, function, column and index of both files is checked, on every start.
export PGHOST="$INZYGHT_PG_HOST" PGPORT="$PG_PORT" PGDATABASE="$PG_DB" PGUSER="$INZYGHT_PG_USER" PGPASSWORD="$INZYGHT_PG_PASSWORD" PGCONNECT_TIMEOUT=5
i=0
until psql -qtAc 'select 1' >/dev/null 2>&1; do
  i=$((i + 1)); [ "$i" -lt 60 ] || { echo "inzyght-entrypoint: PostgreSQL at $PGHOST:$PGPORT/$PGDATABASE does not answer" >&2; exit 1; }
  sleep 2
done
if [ "$(psql -qtAc "select to_regclass('public.blocks') is null")" = t ]; then
  echo "inzyght-entrypoint: empty database: applying schema.sql"
  psql -q -1 -v ON_ERROR_STOP=1 -f "$APP/sql/schema.sql"
fi
out=$(psql -q -c 'set client_min_messages = warning' -f "$APP/sql/schema_reorg_support.sql" 2>&1) || true
bad=$(printf '%s\n' "$out" | grep 'ERROR:' \
  | grep -vE 'ERROR: +relation "idx_(reorg_detected_at|reorg_status|reorg_height|blocks_finalized)" already exists' || true)
[ -z "$bad" ] || { printf 'inzyght-entrypoint: schema_reorg_support.sql failed:\n%s\n' "$bad" >&2; exit 1; }
# Our migration, on every start and before Inzyght runs: blocks.miner_address was varchar(50), which
# cut a 53-character post-quantum address. An index made before the image's schema edit
# (README.md, "What the build changes") is widened here; widening a varchar rewrites nothing, and the
# statement runs only while the column is narrower, so every later start is a no-op.
psql -q -v ON_ERROR_STOP=1 <<'SQL'
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema = 'public' AND table_name = 'blocks' AND column_name = 'miner_address'
               AND data_type = 'character varying' AND character_maximum_length < 128) THEN
    ALTER TABLE public.blocks ALTER COLUMN miner_address TYPE character varying(128);
    RAISE WARNING 'inzyght-entrypoint: blocks.miner_address widened to varchar(128)';
  END IF;
END
$$;
SQL
missing=$(psql -qtA -v ON_ERROR_STOP=1 <<'SQL'
select coalesce(string_agg(kind || ' ' || name, ', ' order by kind, name), '') from (
  select 'relation' as kind, n as name from unnest(array[
      'blocks', 'transactions', 'sync_progress', 'reorg_events', 'reorg_status', 'finalization_progress',
      'idx_blocks_hash', 'idx_blocks_finalized', 'idx_reorg_detected_at', 'idx_reorg_height',
      'idx_reorg_status', 'idx_sync_progress_name', 'idx_sync_progress_status',
      'idx_tx_block_height', 'idx_tx_is_coinbase']) n
    where to_regclass('public.' || n) is null
  union all
  select 'function', n from unnest(array[
      'check_reorg_occurred', 'complete_sync', 'finalize_blocks', 'get_recent_reorg_events',
      'get_sync_progress', 'record_reorg_event', 'rollback_reorg', 'update_sync_progress']) n
    where not exists (select 1 from pg_proc p join pg_namespace s on s.oid = p.pronamespace
                      where s.nspname = 'public' and p.proname = n)
  union all
  select 'column', t || '.' || c from (values
      ('blocks', 'finality_depth'), ('blocks', 'is_finalized'), ('blocks', 'finalized_at'),
      ('transactions', 'affected_by_reorg_count'), ('transactions', 'last_reorg_at'),
      ('sync_progress', 'last_reorg_height'), ('sync_progress', 'last_reorg_time'),
      ('sync_progress', 'last_reorg_depth'), ('sync_progress', 'consecutive_reorg_count')) v(t, c)
    where not exists (select 1 from information_schema.columns
                      where table_schema = 'public' and table_name = t and column_name = c)
) m
SQL
)
[ -z "$missing" ] || { echo "inzyght-entrypoint: the schema is incomplete, missing: $missing" >&2; exit 1; }
echo "inzyght-entrypoint: schema complete"

# Wait until the node answers getblockcount (not during a prefix import or its warm-up): Inzyght
# started earlier only fills its log with connection errors. INZYGHT_WAIT_RPC=0 skips the wait.
if [ "${INZYGHT_WAIT_RPC:-1}" = 1 ]; then
  i=0
  until perl -MHTTP::Tiny -MMIME::Base64 -e '
      my $r = HTTP::Tiny->new(timeout => 10)->post("http://$ENV{INZYGHT_RPC_HOST}:$ENV{INZYGHT_RPC_PORT}/", {
        headers => { "Content-Type" => "application/json",
                     "Authorization" => "Basic " . encode_base64("$ENV{INZYGHT_RPC_USER}:$ENV{INZYGHT_RPC_PASSWORD}", "") },
        content => q({"jsonrpc":"1.0","id":"wait","method":"getblockcount","params":[]}) });
      exit($r->{success} ? 0 : 1)'; do
    [ $((i % 30)) -eq 0 ] && echo "inzyght-entrypoint: waiting for the node's RPC at $INZYGHT_RPC_HOST:$INZYGHT_RPC_PORT"
    i=$((i + 1)); sleep 10
  done
fi

# The backfill for that migration: miners the old 50-character cut left in the index. The index
# holds no outputs (Inzyght reads them from the node), so each such block's coinbase is asked of the
# node: getblock <height> 1, then getrawtransaction <its first txid> 1. A row is rewritten only when
# exactly one address among the coinbase's outputs is longer than the stored 50 characters and
# begins with them; anything else is left as it is and named in the log. A node that does not answer
# only postpones it (the pass ends after three failures in a row): the rows stay cut and the next
# start tries again. Without cut rows, one query.
cut=$(psql -qtA -F ' ' -v ON_ERROR_STOP=1 -c "select height, miner_address from public.blocks where length(miner_address) = 50 order by height") \
  || { echo "inzyght-entrypoint: the query for cut miner addresses failed" >&2; exit 1; }
if [ -n "$cut" ]; then
  echo "inzyght-entrypoint: $(printf '%s\n' "$cut" | wc -l | tr -d ' ') block(s) with a miner address cut at 50 characters: asking the node"
  printf '%s\n' "$cut" | perl -MHTTP::Tiny -MMIME::Base64 -MJSON::PP -e '
      my $http = HTTP::Tiny->new(timeout => 30);
      my $auth = "Basic " . encode_base64("$ENV{INZYGHT_RPC_USER}:$ENV{INZYGHT_RPC_PASSWORD}", "");
      sub rpc {
        my ($method, @params) = @_;
        my $r = $http->post("http://$ENV{INZYGHT_RPC_HOST}:$ENV{INZYGHT_RPC_PORT}/", {
          headers => { "Content-Type" => "application/json", "Authorization" => $auth },
          content => encode_json({ jsonrpc => "1.0", id => "backfill", method => $method, params => \@params }) });
        die "$method: HTTP $r->{status} $r->{reason}\n" unless $r->{success};
        my $d = decode_json($r->{content});
        die "$method: no result\n" unless defined $d->{result};
        return $d->{result};
      }
      my ($failed, $in_a_row) = (0, 0);
      while (my $line = <STDIN>) {
        my ($height, $have) = $line =~ /^(\d+) ([A-Za-z0-9]{50})$/ or next;
        my $tx = eval {
          my $txid = rpc("getblock", "$height", 1)->{tx}[0];
          die "getblock: no transaction id\n" unless defined $txid && !ref $txid && $txid =~ /^[0-9a-f]{64}$/;
          rpc("getrawtransaction", $txid, 1);
        };
        if (!defined $tx) {   # one block the node cannot answer does not hold up the others; a silent node ends the pass
          print STDERR "inzyght-entrypoint: block $height: $@";
          $failed++;
          last if ++$in_a_row >= 3;
          next;
        }
        $in_a_row = 0;
        my %full;
        for my $out (@{ $tx->{vout} || [] }) {
          for my $a (@{ $out->{scriptPubKey}{addresses} || [] }) {
            $full{$a} = 1 if $a =~ /^[A-Za-z0-9]{51,128}$/ && substr($a, 0, 50) eq $have;
          }
        }
        my @full = keys %full;
        if (@full == 1) {
          print "UPDATE public.blocks SET miner_address = \x27$full[0]\x27 WHERE height = $height AND miner_address = \x27$have\x27;\n";
        } else {
          print STDERR "inzyght-entrypoint: block $height: ", scalar(@full), " coinbase output addresses begin with $have; left as it is\n";
        }
      }
      exit($failed ? 1 : 0)' > "$RUN/backfill.sql" \
    || echo "inzyght-entrypoint: the node did not answer for every cut miner address; the rest are tried again on the next start" >&2
  if [ -s "$RUN/backfill.sql" ]; then
    psql -q -1 -v ON_ERROR_STOP=1 -f "$RUN/backfill.sql" \
      || { echo "inzyght-entrypoint: the miner address backfill failed" >&2; exit 1; }
    echo "inzyght-entrypoint: $(wc -l < "$RUN/backfill.sql" | tr -d ' ') miner address(es) restored to full length"
  fi
  rm -f "$RUN/backfill.sql"
fi
unset PGPASSWORD

# Inzyght writes every log line to stdout (the container log, rotated by Docker) and again to
# ./inzyght.log; the file copy would grow without bound in the tmpfs, so it goes to /dev/null.
ln -sfn /dev/null "$RUN/inzyght.log"
exec "$APP/inzyght" "$@"
