# Inzyght's entrypoint (images/inzyght/Dockerfile): renders inzyght.conf and config/drogon_config.json
# from the environment into INZYGHT_RUNDIR, applies Inzyght's PostgreSQL schema to an empty database
# (the binary does not), then execs inzyght there. Every variable is listed in images/inzyght/README.md.
# Secrets come from the environment only and are written to the run directory with mode 0600.
set -eu
APP=/opt/inzyght
RUN="${INZYGHT_RUNDIR:-/run/inzyght}"

need() { eval "v=\${$1:-}"; [ -n "$v" ] || { echo "inzyght-entrypoint: $1 is required" >&2; exit 2; }; }
# A value that goes into the INI file must be one line without a ';' or '#' comment start.
ini() { case "$2" in *"
"*|*\;*|*\#*) echo "inzyght-entrypoint: $1 must be one line without ';' or '#'" >&2; exit 2 ;; esac; }

need INZYGHT_RPC_HOST; need INZYGHT_RPC_PORT; need INZYGHT_RPC_USER; need INZYGHT_RPC_PASSWORD
need INZYGHT_PG_HOST; need INZYGHT_PG_USER; need INZYGHT_PG_PASSWORD
for k in INZYGHT_RPC_PASSWORD INZYGHT_PG_PASSWORD INZYGHT_RPC_USER INZYGHT_PG_USER; do eval "ini $k \"\$$k\""; done
# Inzyght turns a PostgreSQL host of localhost or 127.0.0.1 into the Unix socket /var/run/postgresql
# (src/main.cc), which this container does not have: give it a name or a non-loopback address.
case "$INZYGHT_PG_HOST" in localhost|127.0.0.1)
  echo "inzyght-entrypoint: INZYGHT_PG_HOST=$INZYGHT_PG_HOST means the Unix socket to Inzyght; use a host name or address it reaches over TCP" >&2; exit 2 ;;
esac

PG_PORT="${INZYGHT_PG_PORT:-5432}"
PG_DB="${INZYGHT_PG_DATABASE:-inzyght}"
PORT="${INZYGHT_PORT:-8080}"
THREADS="${INZYGHT_THREADS:-4}"
ZMQ="${INZYGHT_ZMQ_ENDPOINT:-}"
[ -n "$ZMQ" ] && ZMQ_ON=true || ZMQ_ON=false

mkdir -p "$RUN/config" "$RUN/logs"
cd "$RUN"
ln -sfn "$APP/public" "$RUN/public"
umask 077
cat > inzyght.conf <<EOF
# generated by inzyght-entrypoint from the environment; do not edit
[server]
host = 0.0.0.0
port = $PORT
threads = $THREADS
enable_logging = true
log_level = ${INZYGHT_LOG_LEVEL:-INFO}
log_path = ./logs

[database]
type = postgresql
timeout = 30

[rpc]
host = $INZYGHT_RPC_HOST
port = $INZYGHT_RPC_PORT
username = $INZYGHT_RPC_USER
password = $INZYGHT_RPC_PASSWORD
timeout = ${INZYGHT_RPC_TIMEOUT:-60.0}
ssl = false
validate_certificate = false

[zeromq]
enabled = $ZMQ_ON
endpoint = ${ZMQ:-tcp://127.0.0.1:1}
polling_fallback_timeout = ${INZYGHT_POLLING_FALLBACK_TIMEOUT:-300}
polling_interval = ${INZYGHT_POLLING_INTERVAL:-120}

[connection]
pool_size = 10
connection_timeout = 5.0
reconnect_attempts = 3

[api]
enabled = true
version = v1
max_connections = 100
max_body_size = 1048576
enable_cors = false

[postgresql]
host = $INZYGHT_PG_HOST
port = $PG_PORT
database = $PG_DB
username = $INZYGHT_PG_USER
password = $INZYGHT_PG_PASSWORD
query_pool_size = ${INZYGHT_PG_QUERY_POOL:-8}

[indexer]
block_batch_size = ${INZYGHT_BLOCK_BATCH_SIZE:-25}
block_headers_batch_size = ${INZYGHT_BLOCK_HEADERS_BATCH_SIZE:-1000}
queue_depth = ${INZYGHT_QUEUE_DEPTH:-5}

[security]
enable_ssl = false
enable_rate_limit = ${INZYGHT_RATE_LIMIT:-true}

[session]
enabled = false
timeout = 3600
storage = memory

[rate_limit]
trust_proxy = ${INZYGHT_TRUST_PROXY:-false}
trusted_proxies = ${INZYGHT_TRUSTED_PROXIES:-127.0.0.1,::1}
address_max_requests = ${INZYGHT_ADDRESS_MAX_REQUESTS:-20}
address_window_seconds = 60
api_max_requests = ${INZYGHT_API_MAX_REQUESTS:-120}
api_window_seconds = 60
EOF

# Drogon's own settings (config/drogon_config.json.example), with the listener on INZYGHT_PORT and
# TLS off: TLS is the reverse proxy's job in the explorer stack.
cat > config/drogon_config.json <<EOF
{
  "app": {
    "name": "inzyght",
    "document_root": "./public",
    "static_files_cache_time": 86400,
    "file_types": ["html","js","css","ico","png","jpg","jpeg","gif","svg","woff","woff2","ttf","eot","json","txt","mp4","webm","zip","pdf"],
    "upload_path": "$RUN/uploads",
    "max_connections": 1000,
    "client_max_body_size": "1M",
    "server_header_field": "Server: Inzyght",
    "enable_session": false,
    "session_timeout": 0,
    "log": {
      "log_path": "./logs/",
      "logfile_base_name": "inzyght_drogon",
      "log_level_index": 3,
      "max_log_file_size": 104857600,
      "enable_auto_rotating": true
    },
    "run_as_daemon": false,
    "relaunch_on_error": false,
    "use_subprocesses": false,
    "number_of_threads": $THREADS,
    "reactor_number": 1,
    "enable_unicode_escaping_in_json": true
  },
  "listeners": [ { "address": "0.0.0.0", "port": $PORT, "https": false } ],
  "ssl": { "cert": "", "key": "", "key_password": "", "conf_commands": [] }
}
EOF
umask 022

# The schema (Inzyght's schema.sql, then schema_reorg_support.sql, in the order of its
# setup_postgresql.sh) on an empty database only. schema.sql runs in one transaction and must succeed;
# schema_reorg_support.sql repeats three indexes schema.sql already made, and upstream applies it
# without stopping on errors, so it runs the same way here and the result is checked afterwards.
export PGHOST="$INZYGHT_PG_HOST" PGPORT="$PG_PORT" PGDATABASE="$PG_DB" PGUSER="$INZYGHT_PG_USER" PGPASSWORD="$INZYGHT_PG_PASSWORD" PGCONNECT_TIMEOUT=5
i=0
until psql -qtAc 'select 1' >/dev/null 2>&1; do
  i=$((i + 1)); [ "$i" -lt 60 ] || { echo "inzyght-entrypoint: PostgreSQL at $PGHOST:$PGPORT/$PGDATABASE does not answer" >&2; exit 1; }
  sleep 2
done
if [ "$(psql -qtAc "select to_regclass('public.blocks') is null")" = t ]; then
  echo "inzyght-entrypoint: empty database: applying schema.sql and schema_reorg_support.sql"
  psql -q -1 -v ON_ERROR_STOP=1 -f "$APP/sql/schema.sql"
  psql -q -f "$APP/sql/schema_reorg_support.sql" 2>&1 | grep -v 'already exists' || true
  ok=$(psql -qtAc "select (to_regprocedure('public.finalize_blocks(integer,integer)') is not null or exists (select 1 from pg_proc where proname = 'finalize_blocks')) and exists (select 1 from information_schema.columns where table_name = 'blocks' and column_name = 'is_finalized')")
  [ "$ok" = t ] || { echo "inzyght-entrypoint: the schema did not apply completely" >&2; exit 1; }
  echo "inzyght-entrypoint: schema applied"
fi
unset PGPASSWORD

# Wait until the node answers getblockcount (not during a prefix import or its warm-up): Inzyght
# started earlier only fills its log with connection errors. INZYGHT_WAIT_RPC=0 skips the wait.
if [ "${INZYGHT_WAIT_RPC:-1}" = 1 ]; then
  i=0
  until perl -MHTTP::Tiny -MMIME::Base64 -e '
      my $r = HTTP::Tiny->new(timeout => 10)->post("http://$ENV{INZYGHT_RPC_HOST}:$ENV{INZYGHT_RPC_PORT}/", {
        headers => { "Content-Type" => "application/json",
                     "Authorization" => "Basic " . encode_base64("$ENV{INZYGHT_RPC_USER}:$ENV{INZYGHT_RPC_PASSWORD}", "") },
        content => q({"jsonrpc":"1.0","id":"wait","method":"getblockcount","params":[]}) });
      exit($r->{success} ? 0 : 1)'; do
    [ $((i % 30)) -eq 0 ] && echo "inzyght-entrypoint: waiting for the node's RPC at $INZYGHT_RPC_HOST:$INZYGHT_RPC_PORT"
    i=$((i + 1)); sleep 10
  done
fi

# Inzyght writes every log line to stdout (the container log, rotated by Docker) and again to
# ./inzyght.log; the file copy would grow without bound in the tmpfs, so it goes to /dev/null.
ln -sfn /dev/null "$RUN/inzyght.log"
exec "$APP/inzyght" "$@"
